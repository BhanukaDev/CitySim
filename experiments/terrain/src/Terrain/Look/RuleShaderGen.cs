using System.Globalization;
using System.Text;
using Godot;

namespace CitySim.TerrainSystem.Look;

/// <summary>
/// Specialises terrain.gdshader for a rule stack: the generic rule loop (between <see cref="BeginMarker"/> and
/// <see cref="EndMarker"/>) becomes straight-line code with only the inputs, range ends and noise each condition uses.
/// <para>
/// Baked (<c>bake: true</c>) the numbers are constants: as fast as the original hand-written rules. Reading them from
/// the <c>rules[]</c> uniform instead cost ~25% of the frame on an M1 (14 rules, 1600×900), and the generic loop more.
/// The uniform version is for live editing: only structural edits (input, layer, open ends, invert, noise on/off,
/// adding or moving rules) change its code, so dragging a slider doesn't recompile. <see cref="Terrain.ApplyLook"/>
/// switches back to a baked shader once edits pause.
/// </para>
/// </summary>
public static class RuleShaderGen
{
    public const string BeginMarker = "// @rules-begin";
    public const string EndMarker = "// @rules-end";

    private const float OpenEnd = 1e5f; // the shader's OPEN_END
    private static readonly string[] InputExpr = ["in0.x", "in0.y", "in0.z", "in0.w", "in1.x", "in1.y", "in1.z", "in1.w", "in2.x", "in2.y", "in2.z"];
    private static readonly string[] NoiseExpr = ["edge_noises.x", "edge_noises.y", "edge_noises.z", "edge_noises.w"];
    private static readonly string[] Channel = ["x", "y", "z", "w"];

    /// <summary>
    /// <paramref name="source"/> with its rule loop replaced by code for <paramref name="packed"/> (from
    /// <see cref="TerrainLook.Pack"/>), or <paramref name="source"/> unchanged if it has no markers.
    /// </summary>
    public static string Specialize(string source, Vector4[] packed, int count, bool bake)
    {
        int begin = source.IndexOf(BeginMarker, System.StringComparison.Ordinal);
        int end = source.IndexOf(EndMarker, System.StringComparison.Ordinal);
        if (begin < 0 || end < begin) return source;
        int lineStart = source.LastIndexOf('\n', begin) + 1;
        int lineEnd = source.IndexOf('\n', end);
        if (lineEnd < 0) lineEnd = source.Length;
        return source[..lineStart] + RulesBlock(packed, count, bake) + source[lineEnd..];
    }

    private static string RulesBlock(Vector4[] p, int count, bool bake)
    {
        var sb = new StringBuilder();
        sb.Append("\t// Generated by RuleShaderGen for the current rule stack (the generic loop is in terrain.gdshader).\n");
        if (count == 0) return sb.ToString();
        sb.Append("\t{\n\tfloat c, v;\n");
        for (int r = 0; r < count; r++)
        {
            int h = r * 4;
            var head = p[h];
            var nz = p[h + 3];
            sb.Append($"\t// rule {r}\n");
            // Each number is either a literal (baked) or its rules[] uniform.
            string U(int i, char comp, float value) => bake ? F(value) : $"rules[{i}].{comp}";
            sb.Append($"\tc = {U(h, 'y', head.Y)};\n");
            Condition(sb, p[h + 1], h + 1, head.Z > 0.5f, nz.X != 0f, (int)nz.Y, U(h + 3, 'x', nz.X), U);
            Condition(sb, p[h + 2], h + 2, head.W > 0.5f, nz.Z != 0f, (int)nz.W, U(h + 3, 'z', nz.Z), U);
            int layer = Mathf.Clamp((int)head.X, 0, 7);
            sb.Append("\tc = clamp(c, 0.0, 1.0);\n");
            sb.Append($"\tif (rule_debug == {r}) debug_cov = c;\n");
            sb.Append($"\twa *= 1.0 - c; wb *= 1.0 - c; {(layer < 4 ? "wa" : "wb")}.{Channel[layer % 4]} += c;\n");
        }
        sb.Append("\t}\n");
        return sb.ToString();
    }

    private static string F(float f) => f.ToString("0.0#########", CultureInfo.InvariantCulture);

    private static void Condition(StringBuilder sb, Vector4 c, int index, bool invert, bool noise, int slot, string noiseAmount,
        System.Func<int, char, float, string> u)
    {
        int input = (int)c.X;
        if (input < 0 || input >= InputExpr.Length) return;
        bool from = c.Y > -OpenEnd, to = c.Z < OpenEnd;
        if (!from && !to)
        {
            // Open at both ends: always 1 (or 0 inverted).
            if (invert) sb.Append("\tc = 0.0;\n");
            return;
        }
        sb.Append($"\tv = {InputExpr[input]}");
        if (noise) sb.Append($" + {NoiseExpr[Mathf.Clamp(slot, 0, NoiseExpr.Length - 1)]} * {noiseAmount}");
        sb.Append(";\n");
        var k = new StringBuilder();
        string inv = u(index, 'w', c.W);
        if (from) k.Append($"ramp((v - {u(index, 'y', c.Y)}) * {inv})");
        if (to)
        {
            if (from) k.Append(" * ");
            k.Append($"(1.0 - ramp((v - {u(index, 'z', c.Z)}) * {inv}))");
        }
        sb.Append(invert ? $"\tc *= 1.0 - {k};\n" : $"\tc *= {k};\n");
    }

}
